/** Spacing scale. Use these instead of ad-hoc dp values. */
@Immutable
object Spacing {
    val xs = 4.dp
    val s = 8.dp
    val m = 12.dp
    val l = 16.dp
    val xl = 24.dp
    val xxl = 32.dp

    /** Widest the single-column layout gets on tablets. */
    val contentMaxWidth = 680.dp

    /** Window width at which the screen switches to two panes. */
    val twoPaneMinWidth = 720.dp
    val inputPaneWidth = 380.dp
}

/** Text styles for mathematics: monospaced so digits and columns line up. */
@Immutable
data class MathStyles(
    val body: TextStyle,
    val bodyBold: TextStyle,
    val input: TextStyle,
    val answer: TextStyle,
    val equation: TextStyle,
)

private val AppMathStyles = MathStyles(
    body = TextStyle(fontFamily = FontFamily.Monospace, fontSize = 14.sp, lineHeight = 21.sp),
    bodyBold = TextStyle(fontFamily = FontFamily.Monospace, fontSize = 14.sp, lineHeight = 21.sp, fontWeight = FontWeight.Bold),
    input = TextStyle(fontFamily = FontFamily.Monospace, fontSize = 20.sp, lineHeight = 28.sp, fontWeight = FontWeight.Medium),
    answer = TextStyle(fontFamily = FontFamily.Monospace, fontSize = 30.sp, lineHeight = 38.sp, fontWeight = FontWeight.Bold),
    equation = TextStyle(fontFamily = FontFamily.Monospace, fontSize = 15.sp, lineHeight = 22.sp),
)

val LocalMathStyles = staticCompositionLocalOf { AppMathStyles }

@Composable
fun AppTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    content: @Composable () -> Unit,
) {
    MaterialTheme(
        colorScheme = if (darkTheme) DarkColors else LightColors,
        typography = AppTypography,
        shapes = AppShapes,
        content = content,
    )
}
